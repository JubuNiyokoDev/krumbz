import type { Localized, PlatformLocale } from "@/lib/tenant/types";

/** Picks the locale text, falling back to French (always present). */
export function tx(value: Localized | null | undefined, locale: PlatformLocale): string {
  if (!value) return "";
  return value[locale] ?? value.fr;
}

export function isLocalized(value: unknown): value is Localized {
  return typeof value === "object" && value !== null && typeof (value as { fr?: unknown }).fr === "string";
}

/** Replaces `{name}` placeholders. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

